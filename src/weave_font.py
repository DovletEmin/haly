MARKS = {
    # single knots blur into the pile, so marks are two knots wide and sit
    # one clear row above the letter
    'umlaut': {-2: '##.##'},
    'caron': {-2: '.###.'},
    'acute': {-2: '..##.'},
    'cedilla': {7: '.##..'},
}

COMPOSED = {
    'Ä': ('A', 'umlaut'), 'Ö': ('O', 'umlaut'), 'Ü': ('U', 'umlaut'),
    'Ç': ('C', 'cedilla'), 'Ş': ('S', 'cedilla'),
    'Ň': ('N', 'caron'), 'Ž': ('Z', 'caron'), 'Ý': ('Y', 'acute'),
}

TOP, BOTTOM = -2, 7      # rows a glyph may use


def glyph(ch):
    """Rows -2..8 for one character, or None if the alphabet lacks it."""
    if ch in BASE:
        rows = {i: r for i, r in enumerate(BASE[ch])}
        return rows
    if ch in COMPOSED:
        base, mark = COMPOSED[ch]
        rows = {i: r for i, r in enumerate(BASE[base])}
        rows.update(MARKS[mark])
        return rows
    return None


def clean(text, limit=None):
    """Upper-case, drop what cannot be woven, and say so."""
    out, dropped = [], set()
    for ch in ' '.join(text.split()).upper():
        if glyph(ch) is None:
            dropped.add(ch)
        else:
            out.append(ch)
    if dropped:
        print('haly: cannot weave %s in an inscription, left out.'
              % ' '.join(sorted(dropped)), file=sys.stderr)
    s = ''.join(out).strip()
    if limit and len(s) > limit:
        print('haly: inscription cut to %d characters.' % limit, file=sys.stderr)
        s = s[:limit].rstrip()
    return s


def render(text):
    """(knots {(x, y): True}, width) with the baseline row 0 at y = 0."""
    knots, x = set(), 0
    for i, ch in enumerate(text):
        rows = glyph(ch)
        w = len(rows[0])
        for y, row in rows.items():
            for dx, c in enumerate(row):
                if c == '#':
                    knots.add((x + dx, y))
        x += w + (1 if i < len(text) - 1 else 0)
    return knots, x
